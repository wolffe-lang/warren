#!/usr/bin/env python3
"""Generate the pure VT width decision tree from digest-pinned UCD files.

Run with Python -I. Inputs are data only; no module is imported from their
location. --check verifies both derived artifacts without writing them.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIMIT = 0x110000


def digest(data):
    return hashlib.sha256(data).hexdigest()


def interval(text):
    ends = text.strip().split('..')
    low, high = int(ends[0], 16), int(ends[-1], 16)
    assert 0 <= low <= high < LIMIT
    return low, high


def properties(data):
    for raw in data.decode('utf-8').splitlines():
        body = raw.partition('#')[0].strip()
        if body:
            fields = [f.strip() for f in body.split(';')]
            assert len(fields) >= 2
            low, high = interval(fields[0])
            yield low, high, fields[1]


def categories(data):
    result = bytearray(LIMIT)  # 1 Mn/Me; 2 Cf; 0 every other category
    first = None
    for raw in data.decode('utf-8').splitlines():
        fields = raw.split(';')
        assert len(fields) == 15
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        assert 0 <= cp < LIMIT
        tag = 1 if category in ('Mn', 'Me') else 2 if category == 'Cf' else 0
        if name.endswith(', First>'):
            assert first is None
            first = (cp, category, tag)
        elif name.endswith(', Last>'):
            assert first is not None and first[1] == category
            low, _, old_tag = first
            result[low:cp + 1] = bytes([old_tag]) * (cp - low + 1)
            first = None
        else:
            assert first is None
            result[cp] = tag
    assert first is None
    return result


def make_ranges(inputs):
    widths = bytearray([1]) * LIMIT
    for name, wanted in [('EastAsianWidth.txt', {'W', 'F'}),
                         ('emoji-data.txt', {'Emoji_Presentation'})]:
        for low, high, prop in properties(inputs[name]):
            if prop in wanted:
                widths[low:high + 1] = b'\x02' * (high - low + 1)
    cats = categories(inputs['UnicodeData.txt'])
    for cp, category in enumerate(cats):
        if category == 1:
            widths[cp] = 0
    for low, high, prop in properties(inputs['DerivedCoreProperties.txt']):
        if prop == 'Default_Ignorable_Code_Point':
            for cp in range(low, high + 1):
                if cats[cp] == 2:
                    widths[cp] = 0
    widths[0x200B:0x2010] = b'\0' * 5
    ranges = []
    at = 0
    while at < LIMIT:
        end, value = at, widths[at]
        while end + 1 < LIMIT and widths[end + 1] == value:
            end += 1
        if value != 1:
            ranges.append([at, end, value])
        at = end + 1
    return ranges


def tree(ranges, depth=1):
    indent = '    ' * depth
    if not ranges:
        return [indent + 'return 1']
    middle = len(ranges) // 2
    low, high, value = ranges[middle]
    lines = [indent + 'if cp < %d {' % low]
    lines += tree(ranges[:middle], depth + 1)
    lines += [indent + '} else if cp > %d {' % high]
    lines += tree(ranges[middle + 1:], depth + 1)
    lines += [indent + '} else {', indent + '    return %d' % value, indent + '}']
    return lines


def render(version, ranges):
    lines = ['//! member: true',
             '//! Generated by tools/vt/generate_widths.py; do not edit.',
             '//! Data: Unicode %s, copyright Unicode, Inc.; see LICENSE-UNICODE.' % version,
             '//! SPDX-License-Identifier: GPL-3.0-or-later AND Unicode-3.0', '',
             '/// The pinned normative width-data version; locale independent.',
             'pub fn width_version() -> str { "%s" }' % version, '',
             '/// Natural width: Mn/Me and default-ignorable Cf are zero; EAW W/F',
             '/// or Emoji_Presentation are two (zero wins); otherwise one. This',
             '/// does not execute controls, join emoji, or validate scalar input.',
             '/// Parser validation precedes it; out-of-range integers return one.',
             'pub fn scalar_width(cp: int) -> int {',
             '    if cp < 128 || cp > 1114111 { return 1 }']
    lines += tree(ranges)
    return '\n'.join(lines + ['}', ''])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--data-dir', type=Path, required=True)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    pin = json.loads((ROOT / 'tests/vt/unicode-sources.json').read_text())
    base = args.data_dir.resolve()
    inputs = {}
    for source in pin['sources']:
        matches = list(base.rglob(source['name']))
        assert len(matches) == 1, source['name']
        path = matches[0].resolve()
        assert path.is_relative_to(base) and path.stat().st_size <= 16 * 1024 * 1024
        data = path.read_bytes()
        assert digest(data) == source['sha256'], source['name']
        assert digest(path.read_bytes()) == source['sha256'], source['name']
        inputs[source['name']] = data
    ranges = make_ranges(inputs)
    code = render(pin['version'], ranges)
    metadata = {'schema': 1, 'version': pin['version'], 'sources': pin['sources'],
                'algorithm': pin['algorithm'], 'ranges': ranges,
                'generated_sha256': digest(code.encode())}
    encoded = json.dumps(metadata, indent=2) + '\n'
    for path, text in [(ROOT / 'src/vt/width.lu', code),
                       (ROOT / 'tests/vt/width-ranges.json', encoded)]:
        if args.check:
            assert path.read_text() == text, str(path)
        else:
            path.write_text(text)
    print('PASS width-generation unicode=%s ranges=%d generated=%s' %
          (pin['version'], len(ranges), metadata['generated_sha256']))


if __name__ == '__main__':
    main()
